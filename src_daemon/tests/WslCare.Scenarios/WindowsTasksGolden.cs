using System.Text.Json;
using System.Text.Json.Nodes;

using WslCare.Core.Actions.Engine;
using WslCare.Core.Config;
using WslCare.Core.Files;
using WslCare.Core.Json;
using WslCare.Core.Scheduler;
using WslCare.TestSupport;

namespace WslCare.Scenarios;

/// <summary>
/// <c>contracts/golden/windows-tasks-render.json</c> (WR-D1 of PLAN_windows_runner.md §3.2, §5): the answers of
/// <c>tasks render &lt;watch|archive&gt; --json</c> under the embedded defaults, for a fixed SID and a fixed staged path — built from
/// the product's own pure parts (<see cref="TasksRender.Report"/>, <see cref="WindowsTaskDefinitions"/>, <see cref="StagedCopies"/>,
/// <see cref="DryRunWindow.Peek"/>), so it runs on every OS and every value in it is one the product computed. The extension's
/// WR-E1 fake replays these answers and its WR-E2 Windows leg parses the XML with Task Scheduler and compares the read-back's
/// summary with the one here. Checked and regenerated by <see cref="ContractFilesTests"/> (<c>WSL_CARE_WRITE_GOLDENS=1</c>).
/// </summary>
internal static class WindowsTasksGolden
{
    public const string File = "golden/windows-tasks-render.json";

    /// <summary>A SID of the shape <c>WindowsIdentity.GetCurrent().User</c> answers for a local account — no real account's.</summary>
    public const string Sid = "S-1-5-21-1000000000-2000000000-3000000000-1001";

    /// <summary>A digest of the staged folder's shape — no real build's.</summary>
    public const string Digest = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

    public const string Release = "0.6.0";

    /// <summary>Under the profile name <c>user</c>, the one name a committed golden may carry (<c>FixturePrivacyTests</c>).</summary>
    public const string StagingRoot = "C:\\Users\\user\\AppData\\Local\\wsl-care\\bin";

    public static readonly string StagedExe = $"{StagingRoot}\\{Digest}\\{StagedCopies.ExeName}";

    /// <summary>The extension folder's exe: what a render from the BUNDLED exe answers — never registrable.</summary>
    public const string BundledExe = "C:\\Users\\user\\.vscode\\extensions\\oleksandrdubyna.wsl-care-0.68.0-win32-x64\\bin\\wsl-care.exe";

    public static string Text()
    {
        var config = ConfigLoader.Load([(ConfigLoader.DefaultsFile, new FileReadResult.Content(ConfigLoader.EmbeddedDefaults()))]).Config;
        using var sandbox = new SandboxHost("golden-windows-tasks");
        // An empty state directory: the week not started — the answer before the first task run.
        var dry = DryRunWindow.Peek(sandbox.Paths, sandbox.Files, config, DateTimeOffset.Parse(GoldenContracts.FixedInstant, System.Globalization.CultureInfo.InvariantCulture));
        var staged = StagedCopies.VerifiedCopy(StagedExe, Digest, Release);
        // The path check refuses before anything is read, so the bundled exe's answer is the product's on every OS.
        var bundled = StagedCopies.Check(StagingRoot, BundledExe, Release, sandbox.Files, sandbox.Files, config.Int(ConfigKeys.Records.MaxStateFileBytes));
        return ContractFilesTests.Indented(new JsonObject
        {
            ["schemaVersion"] = 1,
            ["description"] = "The answers of `wsl-care tasks render <task> --json` under the embedded defaults, for a fixed SID and staging root (no real account, no real build): the two tasks from a verified staged copy (registrable), and the watch from the extension folder's exe (not registrable). Built from the daemon's pure parts by ContractFilesTests; the extension's fake replays them and its Windows leg compares Task Scheduler's read-back of each xml with its summary.",
            ["answers"] = new JsonArray(
                Answer("watch from the staged copy", TasksRender.Report(WindowsTask.Watch, config, new TaskIdentity(Sid, StagedExe), staged, dry)),
                Answer("archive from the staged copy", TasksRender.Report(WindowsTask.Archive, config, new TaskIdentity(Sid, StagedExe), staged, dry)),
                Answer("watch from the extension folder", TasksRender.Report(WindowsTask.Watch, config, new TaskIdentity(Sid, BundledExe), bundled, dry))),
        });
    }

    private static JsonObject Answer(string name, TasksRenderReport report) => new()
    {
        ["name"] = name,
        ["argv"] = new JsonArray("tasks", "render", report.Task, "--json"),
        ["answer"] = JsonNode.Parse(JsonSerializer.Serialize(report, WslCareJsonContext.Default.TasksRenderReport)),
    };
}
